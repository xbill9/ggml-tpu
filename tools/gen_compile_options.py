"""Write XLA's default CompileOptionsProto as a C byte array.

PJRT_Client_Compile takes the compile options as a serialized protobuf. The PJRT executor
embeds the bytes this script writes, so neither protobuf nor Python is needed at run time.
usage: python3 gen_compile_options.py OUT.inc
"""
import sys

out = sys.argv[1]
try:
    from jax._src.lib import xla_client as xc
    data = xc.CompileOptions().SerializeAsString()
    src = "jax " + __import__("jax").__version__
except Exception as e:  # no JAX: empty options, which the plugin may or may not accept
    data = b""
    src = "none (" + type(e).__name__ + ")"

with open(out, "w") as f:
    f.write(f"// generated by tools/gen_compile_options.py from {src}\n")
    f.write(f'static const char k_compile_options_src[] = "{src}";\n')
    f.write("static const unsigned char k_compile_options[] = {")
    f.write(",".join(str(b) for b in data) or "0")
    f.write("};\n")
    f.write(f"static const size_t k_compile_options_size = {len(data)};\n")
